// Dates offset helper based on fixed reference date
const getDateOffset = (offsetDays: number) => {
  const d = new Date(`${REFERENCE_DATE}T00:00:00`);
  d.setDate(d.getDate() + offsetDays);
  return d.toISOString().split("T")[0];
};

